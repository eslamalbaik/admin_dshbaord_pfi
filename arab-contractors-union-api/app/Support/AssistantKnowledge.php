    public static function build(): string
    {
        return Cache::remember('assistant_knowledge_v1', 600, fn () => self::compose());
    }

    private static function strip(?string $html, int $max): string
    {
        $t = trim(preg_replace('/\s+/u', ' ', strip_tags((string) $html)));

        return mb_strlen($t) > $max ? mb_substr($t, 0, $max) . '…' : $t;
    }

    private static function compose(): string
    {
        $parts = [self::CONTACT];

        $board = collect(self::BOARD)->map(fn ($m) => "- {$m[0]}: {$m[1]}" . ($m[2] ? " ({$m[2]})" : '') . ($m[3] ? "، {$m[3]}" : '') . ($m[4] ? ". {$m[4]}" : ''))->implode("\n");
        $parts[] = "مجلس الإدارة (الدورة الحالية):\n" . $board;

        $services = collect(self::SERVICES)->map(fn ($s) => "- {$s[0]}: {$s[1]} ({$s[2]})")->implode("\n");
        $parts[] = "خدمات الاتحاد:\n" . $services;

        $faqs = Faq::where('is_active', true)->orderBy('sort')->orderBy('id')->get(['question', 'answer'])
            ->map(fn ($f) => "س: {$f->question}\nج: " . self::strip($f->answer, 600))->implode("\n");
        if ($faqs) {
            $parts[] = "الأسئلة الشائعة:\n" . $faqs;
        }

        $news = News::published()->latest('published_at')->take(8)->get(['title', 'excerpt', 'published_at'])
            ->map(fn ($n) => '- ' . $n->published_at?->format('Y-m-d') . ': ' . $n->title . ($n->excerpt ? ' — ' . self::strip($n->excerpt, 160) : ''))->implode("\n");
        if ($news) {
            $parts[] = "آخر الأخبار:\n" . $news;
        }

        $tenders = Tender::where('status', 'open')->orderBy('deadline')->take(8)->get(['title', 'issuing_entity', 'deadline'])
            ->map(fn ($t) => '- ' . $t->title . ($t->issuing_entity ? " ({$t->issuing_entity})" : '') . ($t->deadline ? ' — آخر موعد ' . \Carbon\Carbon::parse($t->deadline)->format('Y-m-d') : ''))->implode("\n");
        if ($tenders) {
            $parts[] = "العطاءات المفتوحة حالياً:\n" . $tenders;
        }

        $events = Event::published()->orderBy('event_date')->take(6)->get(['title', 'event_date'])
            ->map(fn ($e) => '- ' . $e->title . ($e->event_date ? ' — ' . \Carbon\Carbon::parse($e->event_date)->format('Y-m-d') : ''))->implode("\n");
        if ($events) {
            $parts[] = "الفعاليات:\n" . $events;
        }

        $terms = Term::where('is_active', true)->orderBy('sort')->get(['type', 'title', 'body'])
            ->map(fn ($t) => ($t->type === 'privacy' ? '[خصوصية] ' : '[شروط] ') . $t->title . ': ' . self::strip($t->body, 280))->implode("\n");
        if ($terms) {
            $parts[] = "الشروط والأحكام وسياسة الخصوصية (مختصر):\n" . $terms;
        }

        return implode("\n\n", $parts);
    }
